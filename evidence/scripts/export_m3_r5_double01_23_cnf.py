#!/usr/bin/env python3
"""Create the q=4,m=3,r=5 finite-factor quotient invariant under (01)(23).

The permutation swaps 0<->1 and 2<->3. It has no fixed letters, so
EVERY nonempty named square-free factor has orbit size exactly two.
Choose the lexicographically smallest member of each orbit; the
length-11 contexts are 43,968 orbit Boolean variables. A satisfying
assignment imposes invariance under ONE double transposition, NOT S4.

All squarefree finite words of lengths 12,13,15 are used, even when
bi-infinite extendibility has not been certified. Under the quotient,
one clause per orbit of length-12 and -13 words enforces separation
at distances 1 and 2, and one clause per orbit of length-15 words
enforces a marked center in every five-consecutive-center window.

SAT plus independent original-window verification would prove an
existence result for bi-infinite sequences. UNSAT of this finite-factor
formula alone is NOT a true-subshift impossibility result.

The public reproduction driver supplies a new temporary output path,
independently audits the generated bytes and verifies the SAT model. From
evidence/, use:
    python3 -B reproduce.py --case double --report ../kbl-double.json
"""
from hashlib import sha256
import os
from pathlib import Path
import tempfile
from time import perf_counter

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / ".build/kbl-q4-m3-r5-double01-23.cnf"
FULL = {11: 87936, 12: 230520, 13: 604608, 15: 4156392}
ORBIT_COUNTS = {n: full // 2 for n, full in FULL.items()}
CLAUSE_COUNT = sum(ORBIT_COUNTS[n] for n in (12, 13, 15))
DOUBLESWAP = (1, 0, 3, 2)


def image_of(word):
    return tuple(DOUBLESWAP[symbol] for symbol in word)


def representative(word):
    conjugate = image_of(word)
    return min(word, conjugate)


def square_suffix(word):
    length = len(word)
    for half in range(1, length // 2 + 1):
        if word[length-2*half:length-half] == word[length-half:length]:
            return True
    return False


def all_squarefree(length):
    """Recursive DFS produces original factors in lexicographic order."""
    prefix = []

    def extend():
        if len(prefix) == length:
            yield tuple(prefix)
            return
        for letter in range(4):
            prefix.append(letter)
            if not square_suffix(prefix):
                yield from extend()
            prefix.pop()

    yield from extend()


def hash_path(path):
    hasher = sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def main():
    start = perf_counter()
    orbit_ids = {}
    named11 = 0
    for word in all_squarefree(11):
        named11 += 1
        other = image_of(word)
        if other == word:
            raise AssertionError("Double-transposition unexpectedly fixed context")
        if word < other:
            orbit_ids[word] = len(orbit_ids) + 1
    if named11 != FULL[11] or len(orbit_ids) != ORBIT_COUNTS[11]:
        raise AssertionError(
            f"Incorrect original/orbit contexts: {named11}, {len(orbit_ids)}"
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    temp_path = None
    stats = {}
    shrunk = {}
    units = {}
    digest = sha256()
    try:
        file_descriptor, temp_path = tempfile.mkstemp(
            prefix=".double01-23-", suffix=".tmp", dir=OUTPUT.parent
        )
        with os.fdopen(file_descriptor, "wb", buffering=1 << 20) as stream:
            header = f"p cnf {len(orbit_ids)} {CLAUSE_COUNT}\n".encode("ascii")
            stream.write(header)
            digest.update(header)

            for n in (12, 13, 15):
                count = 0
                reduction = 0
                unit_count = 0
                original = 0
                for word in all_squarefree(n):
                    original += 1
                    if word != representative(word):
                        continue
                    if n in (12, 13):
                        delta = n-11
                        literals = [
                            -orbit_ids[representative(word[:11])],
                            -orbit_ids[representative(word[delta:delta+11])],
                        ]
                    else:
                        literals = [
                            orbit_ids[representative(word[k:k+11])]
                            for k in range(5)
                        ]
                    unique = sorted(set(literals))
                    if len(unique) < len(literals):
                        reduction += 1
                    if len(unique) == 1:
                        unit_count += 1
                    raw = (" ".join(map(str, unique)) + " 0\n").encode("ascii")
                    stream.write(raw)
                    digest.update(raw)
                    count += 1

                if original != FULL[n] or count != ORBIT_COUNTS[n]:
                    raise AssertionError(
                        f"Incorrect length-{n} original/orbit counts: "
                        f"{original}, {count}"
                    )
                stats[n] = count
                shrunk[n] = reduction
                units[n] = unit_count
                print(
                    f"  n={n} named={original} orbit={count} "
                    f"shortened={reduction} unit={unit_count}", flush=True
                )

        result_sha = digest.hexdigest()
        if OUTPUT.exists():
            existing = hash_path(OUTPUT)
            if existing != result_sha:
                raise ValueError(
                    "Refusing to overwrite different output CNF: "
                    f"expected {result_sha}, existing {existing}"
                )
            state = "EXISTING FILE IDENTICAL"
        else:
            try:
                # Hard-link publication is exclusive; unlike os.replace,
                # it does not silently overwrite a concurrently added CNF.
                os.link(temp_path, OUTPUT)
            except FileExistsError:
                if hash_path(OUTPUT) != result_sha:
                    raise ValueError("Output path changed during generation")
            state = "NEW LOCAL FILE GENERATED"
    finally:
        if temp_path is not None and os.path.exists(temp_path):
            os.unlink(temp_path)

    if hash_path(OUTPUT) != result_sha:
        raise AssertionError("Output CNF SHA does not match generated stream")
    print("DOUBLE TRANSPOSITION (0 1)(2 3) — FINITE QUOTIENT CNF COMPLETE")
    print("  Named squarefree contexts:", named11)
    print("  Context orbit variables:", len(orbit_ids))
    print("  Clauses by source factor length:", stats)
    print("  Shortened clauses by factor length:", shrunk)
    print("  Unit clauses by factor length:", units)
    print("  Total clauses:", CLAUSE_COUNT)
    print("  CNF SHA-256:", result_sha)
    print("  Output size (bytes):", OUTPUT.stat().st_size)
    print("  Local untracked path:", OUTPUT.relative_to(ROOT))
    print("  Output:", state)
    print(f"  Elapsed seconds: {perf_counter()-start:.2f}")
    print("SAT/UNSAT NOT YET CHECKED; no true-subshift result asserted.")


if __name__ == "__main__":
    main()
