#!/usr/bin/env python3
"""Independently certify a q4,m3,r5 swap(0,1)-invariant SAT marker rule.

No imports from the SAT formula exporter, independent CNF auditor, or
previous marker verifier. This script checks the exact input CNF SHA-256,
parses every CaDiCaL SAT variable with a unique-assignment check, verifies
every original 2,495,760 quotient CNF clause against the assignment,
and INDEPENDENTLY tests marker separation and domination on all original
(named, unquotiented) square-free words of lengths 12, 13 and 15.

An independently checked SAT witness gives a genuine shared local rule
for every bi-infinite square-free four-letter word. Finite square-free
factors possibly lacking bi-infinite extensions do not weaken the SAT
upper bound: verifying a SUPERSET of all genuine factors is sufficient.

This script must be run on the user's saved original SAT witness before
any existence theorem is asserted. No SAT claim is pre-recorded as
verified and no publication novelty is implied.

From the research repository root:
    python3 -m scripts.verify_m3_r5_swap01_sat_witness

Reads only:
    experiments/m3/kbl-q4-m3-r5-swap01.cnf
    /tmp/kbl-m3-r5-swap01-result.txt

Does NOT change any repository files, except optional Python bytecode
generated by the Python interpreter under scripts/__pycache__.
"""
from hashlib import sha256
from pathlib import Path
from time import perf_counter

ROOT = Path(__file__).resolve().parent.parent
CNF = ROOT / "experiments/m3/kbl-q4-m3-r5-swap01.cnf"
MODEL = Path("/tmp/kbl-m3-r5-swap01-result.txt")
CNF_SHA256 = "6b5ace8de69b932d0e346a540edd96168d3fd6f806588cbff56d26faa66d0a15"
NUM_VARS = 43968
FACTORS = {11: 87936, 12: 230520, 13: 604608, 15: 4156392}
NUM_CLAUSES = sum(FACTORS[n] // 2 for n in (12, 13, 15))


def require(condition, error):
    if not condition:
        raise ValueError(error)


def swap01(w):
    """Explicitly exchange alphabet symbols 0 and 1, leaving 2 and 3."""
    return tuple((1 if v == 0 else 0 if v == 1 else v) for v in w)


def orbit_key(w):
    other = swap01(w)
    return w if w < other else other


def has_square_suffix(w):
    """Check each possible nonempty square ending at final position."""
    n = len(w)
    for d in range(1, n // 2 + 1):
        start = n - 2*d
        same = True
        for i in range(d):
            if w[start + i] != w[start + d + i]:
                same = False
                break
        if same:
            return True
    return False


def named_squarefree_words(length):
    """Iterative depth-first lexicographic enumeration, four named symbols."""
    pending = [()]
    while pending:
        w = pending.pop()
        if len(w) == length:
            yield w
            continue
        for letter in (3, 2, 1, 0):
            child = w + (letter,)
            if not has_square_suffix(child):
                pending.append(child)


def file_hash(path):
    digest = sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def parse_sat_model():
    raw = MODEL.read_bytes()
    model_sha = sha256(raw).hexdigest()
    status = []
    literals = []
    end_seen = False
    for line_no, raw_line in enumerate(raw.splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith(b"c "):
            continue
        if line.startswith(b"s "):
            require(not status, "Duplicate SAT status")
            status.append(line)
            continue
        if not line.startswith(b"v "):
            raise ValueError(f"Unexpected SAT model line {line_no}: {line[:90]!r}")
        require(not end_seen, "Literals after the final model terminator")
        for token in line.split()[1:]:
            lit = int(token)
            if lit == 0:
                require(not end_seen, "Repeated model terminator")
                end_seen = True
            else:
                require(not end_seen, "Assignment continued after terminator")
                literals.append(lit)
    require(status == [b"s SATISFIABLE"], f"Bad SAT status: {status}")
    require(end_seen, "Missing final model zero")
    require(len(literals) == NUM_VARS,
            f"Expected {NUM_VARS} signed literals, got {len(literals)}")

    assignment = [None] * (NUM_VARS + 1)
    for signed in literals:
        pos = abs(signed)
        require(1 <= pos <= NUM_VARS, f"Out-of-range variable {signed}")
        require(assignment[pos] is None, f"Duplicated variable {pos}")
        assignment[pos] = signed > 0
    require(all(v is not None for v in assignment[1:]),
            "Incomplete SAT model")
    print("SAT assignment SHA-256:", model_sha, flush=True)
    print("Complete signed assignments:", NUM_VARS, flush=True)
    print("Marked orbit classes:", sum(assignment[1:]), flush=True)
    return assignment, model_sha


def check_full_cnf(assignment):
    start = perf_counter()
    require(file_hash(CNF) == CNF_SHA256,
            "Original independently audited quotient CNF SHA-256 changed")
    count = 0
    with CNF.open("rb") as stream:
        header = stream.readline()
        require(header == f"p cnf {NUM_VARS} {NUM_CLAUSES}\n".encode("ascii"),
                f"Unexpected DIMACS header: {header[:100]!r}")
        for raw_clause in stream:
            count += 1
            toks = raw_clause.split()
            require(len(toks) >= 2 and toks[-1] == b"0",
                    f"Malformed DIMACS clause #{count}")
            satisfied = False
            for token in toks[:-1]:
                lit = int(token)
                require(lit != 0 and 1 <= abs(lit) <= NUM_VARS,
                        f"Invalid literal in clause {count}")
                if assignment[abs(lit)] == (lit > 0):
                    satisfied = True
            require(satisfied, f"CNF clause #{count} is falsified")
    require(count == NUM_CLAUSES, f"Wrong CNF clause count {count}")
    print("PHASE 1/3 PASSED: independently checked every quotient CNF clause")
    print("  Verified clauses:", count)
    print("  Pinned CNF SHA-256:", CNF_SHA256)
    print(f"  Elapsed seconds: {perf_counter()-start:.2f}", flush=True)


def build_orbit_index():
    full = 0
    reps = []
    for w in named_squarefree_words(11):
        full += 1
        partner = swap01(w)
        require(partner != w, "Unexpected swap-invariant legal context")
        if w < partner:
            reps.append(w)
    require(full == FACTORS[11], f"Unexpected context census {full}")
    require(len(reps) == NUM_VARS, f"Unexpected orbit census {len(reps)}")
    # The original generator assigned variable numbers in lexicographic
    # order of minimal orbit representatives, using an independent DFS.
    rep_id = {w: i for i, w in enumerate(reps, 1)}
    return rep_id


def check_original_semantics(assignment, rep_id):
    start = perf_counter()
    counts = {}
    for n in (12, 13, 15):
        seen = 0
        for w in named_squarefree_words(n):
            seen += 1
            if n == 12 or n == 13:
                offset = n - 11
                a = rep_id[orbit_key(w[:11])]
                b = rep_id[orbit_key(w[offset:offset+11])]
                require(not (assignment[a] and assignment[b]),
                        f"Marker packing fails in original n={n} word {w}")
            else:
                marked = False
                for offset in range(5):
                    orbit = rep_id[orbit_key(w[offset:offset+11])]
                    if assignment[orbit]:
                        marked = True
                        break
                require(marked, f"Marker domination fails on original word {w}")
        require(seen == FACTORS[n], f"Wrong full original factor census n={n}: {seen}")
        counts[n] = seen
        print(f"  Independently checked all original length-{n} factors: {seen}",
              flush=True)
    print("PHASE 2/3 PASSED: direct ORIGINAL sliding-block semantics")
    print("  Adjacent separation windows:", counts[12])
    print("  Distance-two separation windows:", counts[13])
    print("  Five-position domination windows:", counts[15])
    print(f"  Elapsed seconds: {perf_counter()-start:.2f}", flush=True)


def check_color_symmetry(assignment, rep_id):
    start = perf_counter()
    seen = 0
    for w in named_squarefree_words(11):
        seen += 1
        original_id = rep_id[orbit_key(w)]
        transformed_id = rep_id[orbit_key(swap01(w))]
        require(assignment[original_id] == assignment[transformed_id],
                f"Swap(0,1) invariance fails at {w}")
    require(seen == FACTORS[11], f"Wrong color-invariance context census: {seen}")
    print("PHASE 3/3 PASSED: invariance under swap(0,1) on every named context")
    print("  Named length-11 factors:", seen)
    print(f"  Elapsed seconds: {perf_counter()-start:.2f}", flush=True)


def main():
    start = perf_counter()
    print("q4,m3,r5 — INDEPENDENT SINGLE-TRANSPOSITION SAT RULE AUDIT",
          flush=True)
    assignment, model_sha = parse_sat_model()
    check_full_cnf(assignment)
    representative_ids = build_orbit_index()
    check_original_semantics(assignment, representative_ids)
    check_color_symmetry(assignment, representative_ids)
    print("ALL THREE PHASES PASSED")
    print("CERTIFIED EXISTENCE: shift-equivariant q4,m3,r5 marker rule")
    print("with separation >=3 and domination distance <=2 on EVERY")
    print("bi-infinite quaternary square-free input, invariant under (0 1).")
    print("Model SHA-256:", model_sha)
    print(f"Total elapsed seconds: {perf_counter()-start:.2f}")
    print("No higher symmetry, general m theorem or publication novelty asserted.")


if __name__ == "__main__":
    main()
